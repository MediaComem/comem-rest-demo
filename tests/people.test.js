describe('PATCH /api/people/:id', () => {
  let johnDoe;
  beforeEach(async () => {
    johnDoe = await Person.create({ name: 'John Doe', gender: 'male', birthDate: '1990-03-15' });
  });

  it('should update a person', async () => {
    const res = await supertest(app)
      .patch(`/api/people/${johnDoe.id}`)
      .send({ name: 'Jane Doe', gender: 'female' })
      .expect(200)
      .expect('Content-Type', /json/);

    // Check that only the properties in the request body were changed.
    assert.deepEqual(res.body, {
      birthDate: '1990-03-15T00:00:00.000Z',
      createdAt: johnDoe.createdAt.toISOString(),
      gender: 'female',
      id: johnDoe.id,
      name: 'Jane Doe'
    });

    // Check that the changes have been saved to the database.
    const person = await Person.findById(johnDoe.id).exec();
    assert.deepEqual(toAttributes(person), {
      ...toAttributes(johnDoe),
      gender: 'female',
      name: 'Jane Doe'
    });
  });

  it('should not update a person with invalid data', async () => {
    const res = await supertest(app)
      .patch(`/api/people/${johnDoe.id}`)
      .send({ name: 'Jane Doe', gender: 'robot' })
      .expect(422)
      .expect('Content-Type', /json/);

    assertValidationError(res.body, 'Person', { gender: 'enum' });

    // Check that the person is unchanged in the database (including the valid
    // name).
    const person = await Person.findById(johnDoe.id).exec();
    assert.deepEqual(toAttributes(person), toAttributes(johnDoe));
  });

  it('should not update a person that does not exist', async () => {
    const id = new mongoose.Types.ObjectId().toString();

    const res = await supertest(app)
      .patch(`/api/people/${id}`)
      .send({ name: 'Jane Doe' })
      .expect(404)
      .expect('Content-Type', /text/);

    assert.equal(res.text, `No person found with ID ${id}`);

    // Check that the existing person is unchanged.
    const people = await Person.find().exec();
    assert.deepEqual(people.map(toAttributes), [toAttributes(johnDoe)]);
  });

  it('should not update a person from a request body that is not JSON', async () => {
    const res = await supertest(app)
      .patch(`/api/people/${johnDoe.id}`)
      .type('form')
      .send({ name: 'Jane Doe' })
      .expect(415)
      .expect('Content-Type', /json/);

    assert.deepEqual(res.body, {
      message: 'This resource only has an application/json representation'
    });

    // Check that the person is unchanged in the database.
    const person = await Person.findById(johnDoe.id).exec();
    assert.deepEqual(toAttributes(person), toAttributes(johnDoe));
  });
});

