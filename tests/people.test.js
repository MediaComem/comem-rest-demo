describe('DELETE /api/people/:id', () => {
  let janeSmith;
  let johnSmith;
  let movie;
  beforeEach(async () => {
    [janeSmith, johnSmith] = await Promise.all([
      Person.create({ name: 'Jane Smith', gender: 'female' }),
      Person.create({ name: 'John Smith', gender: 'male' })
    ]);

    // Jane Smith directed a movie, John Smith did not.
    movie = await Movie.create({ title: 'An Amazing Story', directorId: janeSmith.id });
  });

  it('should delete a person', async () => {
    const res = await supertest(app).delete(`/api/people/${johnSmith.id}`).expect(204);

    assert.equal(res.text, '');

    // Check that only that person has been deleted from the database.
    const people = await Person.find().exec();
    assert.deepEqual(people.map(toAttributes), [toAttributes(janeSmith)]);
  });

  it('should not delete a person who directed movies', async () => {
    const res = await supertest(app)
      .delete(`/api/people/${janeSmith.id}`)
      .expect(409)
      .expect('Content-Type', /text/);

    assert.equal(res.text, 'Cannot delete person Jane Smith because movies are directed by them');

    // Check that nothing was deleted from the database.
    const people = await Person.find().sort('name').exec();
    assert.deepEqual(people.map(toAttributes), [toAttributes(janeSmith), toAttributes(johnSmith)]);
    const movies = await Movie.find().exec();
    assert.deepEqual(movies.map(toAttributes), [toAttributes(movie)]);
  });

  it('should not delete a person that does not exist', async () => {
    const id = new mongoose.Types.ObjectId().toString();

    const res = await supertest(app)
      .delete(`/api/people/${id}`)
      .expect(404)
      .expect('Content-Type', /text/);

    assert.equal(res.text, `No person found with ID ${id}`);

    // Check that nothing was deleted from the database.
    const people = await Person.find().sort('name').exec();
    assert.deepEqual(people.map(toAttributes), [toAttributes(janeSmith), toAttributes(johnSmith)]);
  });
});
