describe('PATCH /api/movies/:id', () => {
  let janeSmith;
  let movie;
  beforeEach(async () => {
    janeSmith = await Person.create({ name: 'Jane Smith', gender: 'female' });
    movie = await Movie.create({ title: 'An Amazing Story', rating: 10, directorId: janeSmith.id });
  });

  it('should update a movie', async () => {
    const res = await supertest(app)
      .patch(`/api/movies/${movie.id}`)
      .send({ rating: 8 })
      .expect(200)
      .expect('Content-Type', /json/);

    // Check that only the properties in the request body were changed.
    assert.deepEqual(res.body, {
      createdAt: movie.createdAt.toISOString(),
      directorId: janeSmith.id,
      id: movie.id,
      rating: 8,
      title: 'An Amazing Story'
    });

    // Check that the changes have been saved to the database.
    const updatedMovie = await Movie.findById(movie.id).exec();
    assert.deepEqual(toAttributes(updatedMovie), { ...toAttributes(movie), rating: 8 });
  });

  it('should not update a movie with invalid data', async () => {
    const res = await supertest(app)
      .patch(`/api/movies/${movie.id}`)
      .send({ title: 'An Even More Amazing Story', rating: -1 })
      .expect(422)
      .expect('Content-Type', /json/);

    assertValidationError(res.body, 'Movie', { rating: 'min' });

    // Check that the movie is unchanged in the database (including the valid
    // title).
    const unchangedMovie = await Movie.findById(movie.id).exec();
    assert.deepEqual(toAttributes(unchangedMovie), toAttributes(movie));
  });

  it('should not update a movie that does not exist', async () => {
    const id = new mongoose.Types.ObjectId().toString();

    const res = await supertest(app)
      .patch(`/api/movies/${id}`)
      .send({ rating: 8 })
      .expect(404)
      .expect('Content-Type', /text/);

    assert.equal(res.text, `No movie found with ID ${id}`);

    // Check that the existing movie is unchanged.
    const movies = await Movie.find().exec();
    assert.deepEqual(movies.map(toAttributes), [toAttributes(movie)]);
  });

  it('should not update a movie from a request body that is not JSON', async () => {
    const res = await supertest(app)
      .patch(`/api/movies/${movie.id}`)
      .type('form')
      .send({ rating: 8 })
      .expect(415)
      .expect('Content-Type', /json/);

    assert.deepEqual(res.body, {
      message: 'This resource only has an application/json representation'
    });

    // Check that the movie is unchanged in the database.
    const unchangedMovie = await Movie.findById(movie.id).exec();
    assert.deepEqual(toAttributes(unchangedMovie), toAttributes(movie));
  });
});

