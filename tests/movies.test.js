describe('DELETE /api/movies/:id', () => {
  let janeSmith;
  let amazingStory;
  let badStory;
  beforeEach(async () => {
    janeSmith = await Person.create({ name: 'Jane Smith', gender: 'female' });
    [amazingStory, badStory] = await Promise.all([
      Movie.create({ title: 'An Amazing Story', rating: 10, directorId: janeSmith.id }),
      Movie.create({ title: 'A Bad Story', rating: 2, directorId: janeSmith.id })
    ]);
  });

  it('should delete a movie', async () => {
    const res = await supertest(app).delete(`/api/movies/${badStory.id}`).expect(204);

    assert.equal(res.text, '');

    // Check that only that movie has been deleted from the database, and that
    // its director has not.
    const movies = await Movie.find().exec();
    assert.deepEqual(movies.map(toAttributes), [toAttributes(amazingStory)]);
    const people = await Person.find().exec();
    assert.deepEqual(people.map(toAttributes), [toAttributes(janeSmith)]);
  });

  it('should not delete a movie that does not exist', async () => {
    const id = new mongoose.Types.ObjectId().toString();

    const res = await supertest(app)
      .delete(`/api/movies/${id}`)
      .expect(404)
      .expect('Content-Type', /text/);

    assert.equal(res.text, `No movie found with ID ${id}`);

    // Check that nothing was deleted from the database.
    const movies = await Movie.find().sort('title').exec();
    assert.deepEqual(movies.map(toAttributes), [
      toAttributes(badStory),
      toAttributes(amazingStory)
    ]);
  });
});
