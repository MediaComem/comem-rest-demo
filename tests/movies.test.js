import assert from 'node:assert/strict';
import { after, beforeEach, describe, it } from 'node:test';

import mongoose from 'mongoose';
import supertest from 'supertest';

import app from '../app.js';
import { baseUrl } from '../config.js';
import Movie from '../models/movie.js';
import Person from '../models/person.js';
import { assertValidationError, cleanUpDatabase, getLinks, toAttributes } from './utils.js';

// Clean up leftover data in the database before each test in this file.
beforeEach(cleanUpDatabase);

// Disconnect from the database once the tests are done.
after(() => mongoose.disconnect());

describe('POST /api/movies', () => {
  let janeSmith;
  beforeEach(async () => {
    janeSmith = await Person.create({ name: 'Jane Smith', gender: 'female' });
  });

  it('should create a movie', async () => {
    const res = await supertest(app)
      .post('/api/movies')
      .send({ title: 'An Amazing Story', rating: 10, directorId: janeSmith.id })
      .expect(201)
      .expect('Content-Type', /json/);

    // Check that the response body is the created movie. The ID and creation
    // date are generated by the server, so check their format, then compare the
    // rest of the body exactly.
    const { createdAt, id, ...rest } = res.body;
    assert.match(id, /^[0-9a-f]{24}$/);
    assert.ok(!isNaN(Date.parse(createdAt)));
    assert.deepEqual(rest, {
      directorId: janeSmith.id,
      rating: 10,
      title: 'An Amazing Story'
    });

    // Check that the Location header points to the correct resource.
    assert.equal(res.get('Location'), `${baseUrl}/api/movies/${id}`);

    // Check that the movie has been saved to the database.
    const movie = await Movie.findById(id).exec();
    assert.deepEqual(toAttributes(movie), {
      __v: 0,
      _id: id,
      createdAt: new Date(createdAt),
      directorId: janeSmith.id,
      rating: 10,
      title: 'An Amazing Story'
    });
  });

  it('should create a movie and include its director in the response', async () => {
    const res = await supertest(app)
      .post('/api/movies?include=director')
      .send({ title: 'An Amazing Story', directorId: janeSmith.id })
      .expect(201)
      .expect('Content-Type', /json/);

    const { createdAt, id, ...rest } = res.body;
    assert.match(id, /^[0-9a-f]{24}$/);
    assert.ok(!isNaN(Date.parse(createdAt)));
    assert.deepEqual(rest, {
      director: {
        createdAt: janeSmith.createdAt.toISOString(),
        gender: 'female',
        id: janeSmith.id,
        name: 'Jane Smith'
      },
      directorId: janeSmith.id,
      title: 'An Amazing Story'
    });

    // Check that the movie has been saved to the database (with only the ID of
    // its director).
    const movie = await Movie.findById(id).exec();
    assert.deepEqual(toAttributes(movie), {
      __v: 0,
      _id: id,
      createdAt: new Date(createdAt),
      directorId: janeSmith.id,
      title: 'An Amazing Story'
    });
  });

  it('should not create an invalid movie', async () => {
    const res = await supertest(app)
      .post('/api/movies')
      .send({ title: 'An', rating: 11, directorId: new mongoose.Types.ObjectId().toString() })
      .expect(422)
      .expect('Content-Type', /json/);

    assertValidationError(res.body, 'Movie', {
      directorId: 'user defined',
      rating: 'max',
      title: 'minlength'
    });

    // Check that nothing was saved to the database.
    assert.equal(await Movie.countDocuments().exec(), 0);
  });

  it('should not create a movie with a title that already exists', async () => {
    const movie = await Movie.create({ title: 'An Amazing Story', directorId: janeSmith.id });

    const res = await supertest(app)
      .post('/api/movies')
      .send({ title: 'An Amazing Story', rating: 5, directorId: janeSmith.id })
      .expect(422)
      .expect('Content-Type', /json/);

    assertValidationError(res.body, 'Movie', { title: 'user defined' });

    // Check that the existing movie is the only one, and that it is unchanged.
    const movies = await Movie.find().exec();
    assert.deepEqual(movies.map(toAttributes), [toAttributes(movie)]);
  });

  it('should not create a movie from a request body that is not JSON', async () => {
    const res = await supertest(app)
      .post('/api/movies')
      .type('form')
      .send({ title: 'An Amazing Story', directorId: janeSmith.id })
      .expect(415)
      .expect('Content-Type', /json/);

    assert.deepEqual(res.body, {
      message: 'This resource only has an application/json representation'
    });

    // Check that nothing was saved to the database.
    assert.equal(await Movie.countDocuments().exec(), 0);
  });
});

describe('GET /api/movies', () => {
  let janeSmith;
  let johnSmith;
  let amazingStory;
  let badStory;
  let soSoStory;
  beforeEach(async () => {
    [janeSmith, johnSmith] = await Promise.all([
      Person.create({ name: 'Jane Smith', gender: 'female' }),
      Person.create({ name: 'John Smith', gender: 'male' })
    ]);

    [amazingStory, badStory, soSoStory] = await Promise.all([
      Movie.create({ title: 'An Amazing Story', rating: 10, directorId: janeSmith.id }),
      Movie.create({ title: 'A Bad Story', rating: 2, directorId: janeSmith.id }),
      Movie.create({ title: 'A So-So Story', rating: 4, directorId: johnSmith.id })
    ]);
  });

  /**
   * Returns the expected JSON representation of a movie.
   */
  function movieJson(movie) {
    return {
      createdAt: movie.createdAt.toISOString(),
      directorId: movie.directorId.toString(),
      id: movie.id,
      rating: movie.rating,
      title: movie.title
    };
  }

  it('should retrieve the list of movies', async () => {
    const res = await supertest(app).get('/api/movies').expect(200).expect('Content-Type', /json/);

    // Check that the response body is the list of movies sorted by title.
    assert.deepEqual(res.body, [
      movieJson(badStory),
      movieJson(soSoStory),
      movieJson(amazingStory)
    ]);

    // Everything fits on one page, so there are no pagination links.
    assert.equal(res.get('Link'), undefined);
  });

  it('should retrieve the list of movies with their directors', async () => {
    const res = await supertest(app)
      .get('/api/movies?include=director')
      .expect(200)
      .expect('Content-Type', /json/);

    const janeSmithJson = {
      createdAt: janeSmith.createdAt.toISOString(),
      gender: 'female',
      id: janeSmith.id,
      name: 'Jane Smith'
    };

    assert.deepEqual(res.body, [
      { ...movieJson(badStory), director: janeSmithJson },
      {
        ...movieJson(soSoStory),
        director: {
          createdAt: johnSmith.createdAt.toISOString(),
          gender: 'male',
          id: johnSmith.id,
          name: 'John Smith'
        }
      },
      { ...movieJson(amazingStory), director: janeSmithJson }
    ]);
  });

  it('should retrieve the movies of a director', async () => {
    const res = await supertest(app)
      .get(`/api/movies?directorId=${janeSmith.id}`)
      .expect(200)
      .expect('Content-Type', /json/);

    assert.deepEqual(res.body, [movieJson(badStory), movieJson(amazingStory)]);
  });

  it('should retrieve the movies of several directors', async () => {
    // Also create a movie by another director, which must not be listed.
    const zoeSmith = await Person.create({ name: 'Zoe Smith', gender: 'other' });
    await Movie.create({ title: 'A Strange Story', rating: 7, directorId: zoeSmith.id });

    const res = await supertest(app)
      .get(`/api/movies?directorId=${janeSmith.id}&directorId=${johnSmith.id}`)
      .expect(200)
      .expect('Content-Type', /json/);

    assert.deepEqual(res.body, [
      movieJson(badStory),
      movieJson(soSoStory),
      movieJson(amazingStory)
    ]);
  });

  it('should retrieve the movies with a rating', async () => {
    const res = await supertest(app)
      .get('/api/movies?rating=4')
      .expect(200)
      .expect('Content-Type', /json/);

    assert.deepEqual(res.body, [movieJson(soSoStory)]);
  });

  it('should retrieve the movies within a rating range', async () => {
    const res = await supertest(app)
      .get('/api/movies?ratedAtLeast=3&ratedAtMost=9')
      .expect(200)
      .expect('Content-Type', /json/);

    assert.deepEqual(res.body, [movieJson(soSoStory)]);
  });

  it('should retrieve a page of movies', async () => {
    const res = await supertest(app)
      .get('/api/movies?page=2&pageSize=1')
      .expect(200)
      .expect('Content-Type', /json/);

    // Check that only the second movie (by title) is listed.
    assert.deepEqual(res.body, [movieJson(soSoStory)]);

    // Check that the Link header points to the other pages.
    const url = `${baseUrl}/api/movies`;
    assert.deepEqual(getLinks(res), {
      first: `${url}?page=1&pageSize=1`,
      prev: `${url}?page=1&pageSize=1`,
      next: `${url}?page=3&pageSize=1`,
      last: `${url}?page=3&pageSize=1`
    });
  });
});

