import assert from 'node:assert/strict';
import { after, beforeEach, describe, it } from 'node:test';

import mongoose from 'mongoose';
import supertest from 'supertest';

import app from '../app.js';
import { baseUrl } from '../config.js';
import Movie from '../models/movie.js';
import Person from '../models/person.js';
import { assertValidationError, cleanUpDatabase, getLinks, toAttributes } from './utils.js';

// Clean up leftover data in the database before each test in this file.
beforeEach(cleanUpDatabase);

// Disconnect from the database once the tests are done.
after(() => mongoose.disconnect());

describe('POST /api/people', () => {
  it('should create a person', async () => {
    const res = await supertest(app)
      .post('/api/people')
      .send({ name: 'John Doe', gender: 'male', birthDate: '1990-03-15' })
      .expect(201)
      .expect('Content-Type', /json/);

    // Check that the response body is the created person. The ID and creation
    // date are generated by the server, so check their format, then compare the
    // rest of the body exactly.
    const { createdAt, id, ...rest } = res.body;
    assert.match(id, /^[0-9a-f]{24}$/);
    assert.ok(!isNaN(Date.parse(createdAt)));
    assert.deepEqual(rest, {
      birthDate: '1990-03-15T00:00:00.000Z',
      gender: 'male',
      name: 'John Doe'
    });

    // Check that the Location header points to the correct resource.
    assert.equal(res.get('Location'), `${baseUrl}/api/people/${id}`);

    // Check that the person has been saved to the database.
    const person = await Person.findById(id).exec();
    assert.deepEqual(toAttributes(person), {
      __v: 0,
      _id: id,
      birthDate: new Date('1990-03-15'),
      createdAt: new Date(createdAt),
      gender: 'male',
      name: 'John Doe'
    });
  });

  it('should not create an invalid person', async () => {
    const res = await supertest(app)
      .post('/api/people')
      .send({ name: 'Jo', gender: 'robot' })
      .expect(422)
      .expect('Content-Type', /json/);

    assertValidationError(res.body, 'Person', { gender: 'enum', name: 'minlength' });

    // Check that nothing was saved to the database.
    assert.equal(await Person.countDocuments().exec(), 0);
  });

  it('should not create a person with a name that already exists', async () => {
    const johnDoe = await Person.create({ name: 'John Doe', gender: 'male' });

    const res = await supertest(app)
      .post('/api/people')
      .send({ name: 'John Doe', gender: 'other' })
      .expect(422)
      .expect('Content-Type', /json/);

    assertValidationError(res.body, 'Person', { name: 'user defined' });

    // Check that the existing person is the only one, and that it is unchanged.
    const people = await Person.find().exec();
    assert.deepEqual(people.map(toAttributes), [toAttributes(johnDoe)]);
  });

  it('should not create a person from a request body that is not JSON', async () => {
    const res = await supertest(app)
      .post('/api/people')
      .type('form')
      .send({ name: 'John Doe', gender: 'male' })
      .expect(415)
      .expect('Content-Type', /json/);

    assert.deepEqual(res.body, {
      message: 'This resource only has an application/json representation'
    });

    // Check that nothing was saved to the database.
    assert.equal(await Person.countDocuments().exec(), 0);
  });
});

describe('GET /api/people', () => {
  let janeSmith;
  let johnSmith;
  let zoeSmith;
  beforeEach(async () => {
    // Create 3 people in the database.
    [johnSmith, janeSmith, zoeSmith] = await Promise.all([
      Person.create({ name: 'John Smith', gender: 'male' }),
      Person.create({ name: 'Jane Smith', gender: 'female', birthDate: '1985-07-01' }),
      Person.create({ name: 'Zoe Smith', gender: 'other' })
    ]);

    // Also create 3 movies directed by 2 of those people.
    await Promise.all([
      Movie.create({ title: 'An Amazing Story', rating: 10, directorId: janeSmith.id }),
      Movie.create({ title: 'A Bad Story', rating: 2, directorId: janeSmith.id }),
      Movie.create({ title: 'A So-So Story', rating: 4, directorId: johnSmith.id })
    ]);
  });

  it('should retrieve the list of people', async () => {
    const res = await supertest(app).get('/api/people').expect(200).expect('Content-Type', /json/);

    // Check that the response body is the list of people sorted by name, with
    // the number of movies they directed (people who have not directed any movie
    // must also be listed).
    assert.deepEqual(res.body, [
      {
        birthDate: '1985-07-01T00:00:00.000Z',
        createdAt: janeSmith.createdAt.toISOString(),
        directedMovies: 2,
        gender: 'female',
        id: janeSmith.id,
        name: 'Jane Smith'
      },
      {
        createdAt: johnSmith.createdAt.toISOString(),
        directedMovies: 1,
        gender: 'male',
        id: johnSmith.id,
        name: 'John Smith'
      },
      {
        createdAt: zoeSmith.createdAt.toISOString(),
        directedMovies: 0,
        gender: 'other',
        id: zoeSmith.id,
        name: 'Zoe Smith'
      }
    ]);

    // Everything fits on one page, so there are no pagination links.
    assert.equal(res.get('Link'), undefined);
  });

  it('should retrieve a filtered list of people', async () => {
    const res = await supertest(app)
      .get('/api/people?gender=male')
      .expect(200)
      .expect('Content-Type', /json/);

    assert.deepEqual(res.body, [
      {
        createdAt: johnSmith.createdAt.toISOString(),
        directedMovies: 1,
        gender: 'male',
        id: johnSmith.id,
        name: 'John Smith'
      }
    ]);
  });

  it('should retrieve a page of people', async () => {
    const res = await supertest(app)
      .get('/api/people?page=2&pageSize=1')
      .expect(200)
      .expect('Content-Type', /json/);

    // Check that only the second person is listed.
    assert.deepEqual(res.body, [
      {
        createdAt: johnSmith.createdAt.toISOString(),
        directedMovies: 1,
        gender: 'male',
        id: johnSmith.id,
        name: 'John Smith'
      }
    ]);

    // Check that the Link header points to the other pages.
    const url = `${baseUrl}/api/people`;
    assert.deepEqual(getLinks(res), {
      first: `${url}?page=1&pageSize=1`,
      prev: `${url}?page=1&pageSize=1`,
      next: `${url}?page=3&pageSize=1`,
      last: `${url}?page=3&pageSize=1`
    });
  });

  it('should ignore an invalid page size', async () => {
    const res = await supertest(app)
      .get('/api/people?pageSize=0')
      .expect(200)
      .expect('Content-Type', /json/);

    // Check that the invalid page size is ignored and everyone is listed.
    assert.deepEqual(
      res.body.map(person => person.name),
      ['Jane Smith', 'John Smith', 'Zoe Smith']
    );
  });
});

